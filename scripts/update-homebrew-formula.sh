#!/usr/bin/env bash
# Regenerate Formula/oxide-code.rb for a release tag from its `.sha256` sidecars.
#
# The release workflow runs this after publishing, with the sidecars its build jobs produced.
# To run it by hand, download the sidecars from the published release first:
#
#   gh release download vX.Y.Z --pattern '*.sha256' --dir /tmp/oxide-code-vX.Y.Z
#   ./scripts/update-homebrew-formula.sh vX.Y.Z /tmp/oxide-code-vX.Y.Z

set -euo pipefail

if [[ "$#" -ne 2 ]]; then
  echo "Usage: $0 <vX.Y.Z> <sidecar-dir>" >&2
  exit 2
fi

tag="$1"
sidecars="$2"
if [[ ! "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ ]]; then
  echo "Error: expected a tag such as v1.2.3 or v1.2.3-rc.1 (got: $tag)" >&2
  exit 1
fi

version="${tag#v}"
formula="Formula/oxide-code.rb"
base="https://github.com/hakula139/oxide-code/releases/download/$tag"

# Each `oxide-code-<target>.sha256` sidecar holds `<digest>  <archive>`.
sha() {
  awk '{print $1}' "$sidecars/oxide-code-$1.sha256"
}

mac_arm_sha=$(sha aarch64-apple-darwin)
linux_x86_sha=$(sha x86_64-unknown-linux-gnu)

cat >"$formula" <<EOF
# Regenerated by scripts/update-homebrew-formula.sh for each release the formula follows.
# Edit that script, not this file, when the formula's structure needs to change.

class OxideCode < Formula
  desc "Terminal-based AI coding assistant written in Rust"
  homepage "https://github.com/hakula139/oxide-code"
  url "$base/oxide-code-x86_64-unknown-linux-gnu.tar.gz"
  version "$version"
  sha256 "$linux_x86_sha"
  license "MIT"

  # Every platform needs a URL for the arch requirements below to load and report.
  on_macos do
    depends_on arch: :arm64

    on_arm do
      url "$base/oxide-code-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm_sha"
    end
  end

  on_linux do
    depends_on arch: :x86_64
  end

  def install
    bin.install "ox"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ox --version")
  end
end
EOF

printf 'Updated %s to %s\n' "$formula" "$tag"
